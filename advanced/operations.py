def add(number_1:int, number_2:int):
    """

    :param number_1:
    :param number_2:
    :return: the sum of number_1 and number_2
    """
    number_sum = number_1 + number_2
    return number_sum
def subtract(number_1:int, number_2:int):
    """

    :param number_1:
    :param number_2:
    :return: difference of number_1 and number_2
    """
    return number_1 - number_2
def multiply(number_1:int, number_2:int):
    """

    :param number_1:
    :param number_2:
    :return: multiplication of number_1 and number_2
    """
    return number_1 * number_2
def divide(number_1:int, number_2:int):
    """

    :param number_1:
    :param number_2:
    :return: division of number_1 and number_2
    """
    return number_1 / number_2